'use strict';

// Context Generator — Phase 12K of the Juntia migration.
//
// Assembles `.juntia/context.md` from confirmed facts and confirmed
// decisions only — the final step of FACT → INTERPRETATION → CONFIRMATION
// → DECISION → CONTEXT. Purely mechanical: every line here is either a
// fact `scanProject()` observed or a decision a human actually confirmed
// via `juntia confirm`. Never includes a pending/unconfirmed interpretation
// (Phase 12K's own explicit "no debe contener hipótesis sin confirmar") and
// never invents a section with no real content behind it (no placeholder
// "Constraints"/"Rules" sections — this phase found no real, evidenced
// source for those yet; see the phase doc's own scope note).
//
// Internal-only: not re-exported from lib/index.js (Phase 12C's boundary).

const fs = require('fs');
const path = require('path');

const CONTEXT_DIR = '.juntia';
const CONTEXT_FILE = 'context.md';

function summarizeFacts(facts) {
  const byCategory = (category) => facts.filter((f) => f.category === category);
  const names = (list) => list.map((f) => f.name).join(', ');

  const lines = [];
  const languages = byCategory('language');
  if (languages.length > 0) lines.push(`- Languages: ${names(languages)}`);
  const technologies = byCategory('technology');
  if (technologies.length > 0) lines.push(`- Technologies: ${names(technologies)}`);
  const dependencies = byCategory('dependency');
  if (dependencies.length > 0) {
    lines.push(`- Dependencies: ${dependencies.map((d) => (d.value !== undefined ? `${d.name}@${d.value}` : d.name)).join(', ')}`);
  }
  const manifests = byCategory('manifest');
  if (manifests.length > 0) lines.push(`- Manifests: ${names(manifests)}`);

  return lines.length > 0 ? lines.join('\n') : 'No facts recorded yet — run `juntia analyze` first.';
}

function summarizeDecisions(decisions) {
  if (decisions.length === 0) return 'No decisions confirmed yet — run `juntia analyze --explain` then `juntia confirm`.';
  return decisions
    .map((d) => {
      const flag = d.status === 'conflicted' ? ' [CONFLICTED — see below]' : '';
      return `- ${d.text}${flag} (confirmed ${d.confirmedAt.slice(0, 10)}, based on: ${d.basedOn.join(', ')})`;
    })
    .join('\n');
}

function summarizeConflicts(decisions) {
  const conflicted = decisions.filter((d) => d.status === 'conflicted');
  if (conflicted.length === 0) return null;
  return conflicted
    .map((d) => `- "${d.text}" was based on evidence a recent \`juntia analyze\` no longer found. Not deleted — review with \`juntia confirm\` after checking what changed.`)
    .join('\n');
}

function generateContext(facts, decisions) {
  const lines = [
    '# Project Context',
    '',
    'Machine-generated by `juntia context` from confirmed facts and confirmed decisions only — never from an',
    'unconfirmed interpretation. Do not hand-edit; re-run `juntia context` (or `juntia confirm`, which refreshes',
    'this automatically) after a new decision is confirmed.',
    '',
    '## Facts',
    '',
    summarizeFacts(facts),
    '',
    '## Confirmed decisions',
    '',
    summarizeDecisions(decisions),
  ];

  const conflicts = summarizeConflicts(decisions);
  if (conflicts) {
    lines.push('', '## Conflicts needing review', '', conflicts);
  }

  lines.push('');
  return lines.join('\n');
}

function writeContext(projectRoot, markdown) {
  fs.mkdirSync(path.join(projectRoot, CONTEXT_DIR), { recursive: true });
  fs.writeFileSync(path.join(projectRoot, CONTEXT_DIR, CONTEXT_FILE), markdown);
}

module.exports = { generateContext, writeContext, CONTEXT_FILE };
